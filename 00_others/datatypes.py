a = 10            # integer
b = 3.14          # float
c = "Hello"       # string
d = True          # boolean
e = [1, 2, 3]     # list
f = (4, 5, 6)     # tuple
g = {"name": "Rahul", "age": 25}   # dictionary

print(type(a), a)
print(type(b), b)
print(type(c), c)
print(type(d), d)
print(type(e), e)
print(type(f), f)
print(type(g), g)
